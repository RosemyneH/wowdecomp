// CGInputControl::m_flags, using the 3.3.5 input and movement paths.
// These masks are separate from movement, mouse-mode and vehicle-seat flags.
enum INPUT_CONTROL : uint32_t {
    INPUT_NONE = 0,
    INPUT_TURN_PLAYER = 0x00000001,
    INPUT_TURN_CAMERA = 0x00000002,
    INPUT_MOVE_PLAYER_FORWARD_KEY = 0x00000010,
    INPUT_MOVE_PLAYER_BACKWARD_KEY = 0x00000020,
    INPUT_STRAFE_PLAYER_LEFT_KEY = 0x00000040,
    INPUT_STRAFE_PLAYER_RIGHT_KEY = 0x00000080,
    INPUT_TURN_PLAYER_LEFT_KEY = 0x00000100,
    INPUT_TURN_PLAYER_RIGHT_KEY = 0x00000200,
    INPUT_PITCH_PLAYER_UP_KEY = 0x00000400,
    INPUT_PITCH_PLAYER_DOWN_KEY = 0x00000800,
    INPUT_MOVE_PLAYER_AUTORUN = 0x00001000,
    INPUT_ASCEND_PLAYER_KEY = 0x00002000,
    INPUT_DESCEND_PLAYER_KEY = 0x00004000,
    INPUT_MOVE_PLAYER_SENT = 0x00010000,
    INPUT_STRAFE_PLAYER_SENT = 0x00020000,
    INPUT_TURN_PLAYER_SENT = 0x00040000,
    INPUT_PITCH_PLAYER_SENT = 0x00080000,
    INPUT_ASCEND_DESCEND_PLAYER_SENT = 0x00100000,
    INPUT_TRACKING_MOVE = 0x00200000,
    INPUT_TRACKING_PITCH = 0x00400000,
    INPUT_TRACKING_TURN = 0x01000000,

    INPUT_MOUSE_LOOK_MASK = INPUT_TURN_PLAYER | INPUT_TURN_CAMERA,
    // High look bits are consumed by joystick free look; their writers are absent.
    INPUT_JOYSTICK_LOOK_MASK = 0x06000000,
    INPUT_PLAYER_LOOK_MASK = INPUT_TURN_PLAYER | 0x02000000,
    INPUT_CAMERA_LOOK_MASK = INPUT_TURN_CAMERA | 0x04000000,
    INPUT_FREE_LOOK_MASK = INPUT_MOUSE_LOOK_MASK | INPUT_JOYSTICK_LOOK_MASK,
    INPUT_MOVE_PLAYER_MASK = INPUT_MOVE_PLAYER_FORWARD_KEY | INPUT_MOVE_PLAYER_BACKWARD_KEY,
    INPUT_STRAFE_PLAYER_MASK = INPUT_STRAFE_PLAYER_LEFT_KEY | INPUT_STRAFE_PLAYER_RIGHT_KEY,
    INPUT_TURN_PLAYER_MASK = INPUT_TURN_PLAYER_LEFT_KEY | INPUT_TURN_PLAYER_RIGHT_KEY,
    INPUT_PITCH_PLAYER_MASK = INPUT_PITCH_PLAYER_UP_KEY | INPUT_PITCH_PLAYER_DOWN_KEY,
    INPUT_MOVE_WITH_AUTORUN_MASK = INPUT_MOVE_PLAYER_MASK | INPUT_MOVE_PLAYER_AUTORUN,
    INPUT_MOVE_AND_STRAFE_MASK = INPUT_MOVE_WITH_AUTORUN_MASK | INPUT_STRAFE_PLAYER_MASK,
    INPUT_MOVE_AND_TURN_MASK = INPUT_MOVE_WITH_AUTORUN_MASK | INPUT_TURN_PLAYER_MASK,
    INPUT_MOVE_STRAFE_AND_TURN_MASK = INPUT_MOVE_AND_STRAFE_MASK | INPUT_TURN_PLAYER_MASK,
    INPUT_DIRECTION_KEYS_MASK = INPUT_MOVE_PLAYER_MASK | INPUT_STRAFE_PLAYER_MASK | INPUT_TURN_PLAYER_MASK | INPUT_PITCH_PLAYER_MASK,
    INPUT_HALT_SENT_MASK = INPUT_MOVE_PLAYER_SENT | INPUT_STRAFE_PLAYER_SENT | INPUT_TURN_PLAYER_SENT | INPUT_PITCH_PLAYER_SENT,
    INPUT_MOVE_STOPPED_MASK = INPUT_MOVE_PLAYER_SENT | INPUT_MOVE_PLAYER_AUTORUN,
    // Preserve the unidentified 0x00800000 member of the current tracking masks.
    INPUT_TRACKING_MASK = INPUT_TRACKING_MOVE | INPUT_TRACKING_PITCH | 0x00800000 | INPUT_TRACKING_TURN,
    INPUT_BOBBING_MASK = INPUT_MOVE_AND_STRAFE_MASK | INPUT_TRACKING_MOVE | 0x00800000,
    INPUT_ALL = 0xFFFFFFFF,

    // Unused 0.5.3 names/values; these are not verified 3.3.5 input masks.
    // INPUT_MOVE_PLAYER_OR_TURN_CAMERA = 0x00000004,
    // INPUT_PLAYER_MOVED = 0x10000000,
    // INPUT_CAMERA_MOVED = 0x20000000,
    // INPUT_MOVE_AND_TURN_PLAYER = 0x00000005,
};

